def t(lang: str, key: str, **kwargs) -> str:
    table = STRINGS.get(lang) or STRINGS["zh"]
    template = table.get(key) or STRINGS["zh"].get(key) or key
    try:
        return template.format(**kwargs) if kwargs else template
    except (KeyError, IndexError):
        return template


def localize_note(note: str, lang: str, stale_days: int = 90) -> str:
    """引擎产生的哨兵备注翻译为界面文案（引擎层保持语言无关）。"""
    if note == "__env__":
        return t(lang, "label_env_source")
    if note == "__manual__":
        return t(lang, "label_manual_review")
    if note.startswith("__stale__:"):
        try:
            days = int(note.split(":", 1)[1])
        except ValueError:
            return note
        return t(lang, "stale_warn", days=days, limit=stale_days)
    return note
